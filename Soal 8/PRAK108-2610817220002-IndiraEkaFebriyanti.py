putaran = 5
jarak_tempuh = 14

keliling = jarak_tempuh / putaran
pi = 3.14
r = keliling / (2 * pi)

print("Diketahui : ")
print(f"Pak Dengklek mengelilingi taman = {putaran} Putaran")
print(f"Jarak tempuh Pak Dengklek = {jarak_tempuh} Kilometer\n")

print("Jawaban : ")
print(f"Jari-jari taman yang dikelilingi Pak Dengklek adalah {r:.2f} Kilometer")